def set_cell_font(cell, bold=False, size=12):
    for p in cell.paragraphs:
        p.paragraph_format.first_line_indent = Cm(0)
        p.paragraph_format.line_spacing = 1.0
        for r in p.runs:
            r.font.name = "Times New Roman"; r.font.size = Pt(size); r.font.bold = bold

def para(text="", bold=False, indent=True, align=None, size=14):
    p = doc.add_paragraph()
    if not indent:
        p.paragraph_format.first_line_indent = Cm(0)
    if align is not None:
        p.alignment = align
    r = p.add_run(text)
    r.bold = bold
    if size != 14:
        r.font.size = Pt(size)
    return p

def h1(text):
    return doc.add_heading(text, level=1)

def h2(text):
    return doc.add_heading(text, level=2)

def bullets(items):
    for it in items:
        p = doc.add_paragraph(style="List Bullet")
        p.paragraph_format.first_line_indent = Cm(0)
        p.paragraph_format.line_spacing = 1.5
        p.add_run(it)

def table(headers, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j, hh in enumerate(headers):
        c = t.rows[0].cells[j]; c.text = hh; set_cell_font(c, bold=True, size=12)
    for row in rows:
        cells = t.add_row().cells
        for j, val in enumerate(row):
            cells[j].text = str(val); set_cell_font(cells[j], size=12)
    if widths:
        for j, w in enumerate(widths):
            for r in t.rows:
                r.cells[j].width = Cm(w)
    doc.add_paragraph().paragraph_format.first_line_indent = Cm(0)
    return t

def page_break():
    doc.add_page_break()

